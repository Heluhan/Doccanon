def run_git(root: Path, args: list[str], check: bool = True) -> str:
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if check and result.returncode != 0:
        raise DocCanonError(result.stderr.strip() or "git command failed")
    return result.stdout.strip()


def project_root(value: str | None) -> Path:
    start = Path(value or os.getcwd()).resolve()
    if start.is_file():
        start = start.parent
    result = subprocess.run(
        ["git", "-C", str(start), "rev-parse", "--show-toplevel"],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
    )
    return Path(result.stdout.strip()).resolve() if result.returncode == 0 else start


def scalar(value: str) -> Any:
    value = value.strip()
    if not value:
        return ""
    if value in {"true", "false"}:
        return value == "true"
    if value in {"null", "~"}:
        return None
    if (value.startswith('"') and value.endswith('"')) or (
        value.startswith("'") and value.endswith("'")
    ):
        return value[1:-1]
    try:
        return int(value)
    except ValueError:
        return value


def parse_simple_yaml(text: str) -> dict[str, Any]:
    """Parse the intentionally flat config/frontmatter subset used by DocCanon."""
    data: dict[str, Any] = {}
    current_list: str | None = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("-") and current_list:
            data[current_list].append(scalar(line[1:].strip()))
            continue
        match = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if not match:
            continue
        key, value = match.groups()
        if value:
            data[key] = scalar(value)
            current_list = None
        else:
            data[key] = []
            current_list = key
    return data


def dump_config(data: dict[str, Any]) -> str:
    order = [
        "status",
        "doccanon_version",
        "maturity",
        "docs_root",
        "context_file",
        "required_domains",
        "migration_manifest",
        "feature_manifest",
        "registry",
        "archive_root",
        "agent_entry",
        "agent_adapters",
        "integration_branch",
        "release_branches",
        "development_log_root",
        "release_log_root",
        "reason",
        "decided_at",
    ]
    lines: list[str] = []
    for key in order:
        if key not in data or data[key] is None:
            continue
        value = data[key]
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"  - {json.dumps(str(item), ensure_ascii=False)}" for item in value)
            continue
        if isinstance(value, bool):
            rendered = "true" if value else "false"
        elif isinstance(value, int):
            rendered = str(value)
        else:
            rendered = json.dumps(str(value), ensure_ascii=False)
        lines.append(f"{key}: {rendered}")
    return "\n".join(lines) + "\n"


def load_config(root: Path) -> dict[str, Any] | None:
    path = root / CONFIG_NAME
    if not path.exists():
        return None
    data = parse_simple_yaml(path.read_text(encoding="utf-8"))
    if data.get("status") not in {"enabled", "disabled"}:
        raise DocCanonError(f"Invalid status in {CONFIG_NAME}")
    if data["status"] == "enabled":
        data.setdefault("maturity", "bootstrapping")
        if data["maturity"] not in MATURITIES:
            raise DocCanonError(f"Invalid maturity in {CONFIG_NAME}")
        data.setdefault("required_domains", [])
        data.setdefault("archive_root", DEFAULT_ARCHIVE_ROOT)
        data.setdefault("agent_entry", DEFAULT_AGENT_ENTRY)
        data.setdefault("agent_adapters", list(DEFAULT_AGENT_ADAPTERS))
        data.setdefault("release_branches", [])
        data.setdefault("development_log_root", "docs/development")
        data.setdefault("release_log_root", "docs/releases")
    return data


def config_list(config: dict[str, Any], key: str, default: list[str]) -> list[str]:
    value = config.get(key, default)
    if value is None:
        return []
    if isinstance(value, list):
        return [str(item) for item in value]
    if isinstance(value, str):
        stripped = value.strip()
        if stripped in {"", "[]"}:
            return []
        return [stripped]
    return [str(value)]


def write_config(root: Path, data: dict[str, Any]) -> None:
    target = root / CONFIG_NAME
    rendered = dump_config(data)
    if target.is_file() and target.read_text(encoding="utf-8") == rendered:
        return
    temp = target.with_suffix(target.suffix + ".tmp")
    temp.write_text(rendered, encoding="utf-8")
    temp.replace(target)


def skill_version() -> str:
    path = Path(__file__).resolve().parent.parent / "SKILL.md"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return "unknown"
    match = re.search(r'(?m)^\s+version:\s*"?([^"\n]+?)"?\s*$', text)
    return match.group(1).strip() if match else "unknown"


def install_provenance() -> dict[str, Any]:
    raw = Path(__file__)
    skill_dir = raw.parent.parent
    try:
        resolved = skill_dir.resolve()
    except OSError:
        resolved = skill_dir
    method = "unknown"
    installed_version: str | None = None
    marker = skill_dir / ".doccanon-install.json"
    if os.path.islink(raw) or os.path.islink(skill_dir):
        method = "symlink"
    elif marker.is_file():
        method = "install.py"
        try:
            payload = json.loads(marker.read_text(encoding="utf-8"))
            installed_version = str(payload.get("version", "unknown"))
        except (OSError, json.JSONDecodeError):
            installed_version = "unknown"
    git_repo: str | None = None
    try:
        result = subprocess.run(
            ["git", "-C", str(resolved), "rev-parse", "--show-toplevel"],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
        )
        if result.returncode == 0:
            git_repo = result.stdout.strip()
            if method == "unknown":
                method = "git-clone"
    except OSError:
        pass
    hints = {
        "symlink": "Update the source checkout behind the symlink, then start a new agent session.",
        "install.py": "Update the source checkout and rerun the same install.py command; owned copies are backed up.",
        "git-clone": "Update this checkout and refresh any managed install; or reinstall with your host's skill manager.",
        "unknown": "Reinstall or update with your host's skill manager, for example gh skill update for gh-managed skills.",
    }
    return {
        "method": method,
        "version": skill_version(),
        "installed_version": installed_version,
        "path": str(skill_dir),
        "resolved_path": str(resolved),
        "git_repo": git_repo,
        "update_hint": hints[method],
    }


def template_path(name: str) -> Path:
    return Path(__file__).resolve().parent.parent / "assets" / name


def ensure_base_docs(root: Path, config: dict[str, Any]) -> list[str]:
    created: list[str] = []
    context = root / str(config["context_file"])
    docs_root = root / str(config["docs_root"])
    docs_index = docs_root / "README.md"
    if not context.exists():
        context.write_text(template_path("CONTEXT.md").read_text(encoding="utf-8"), encoding="utf-8")
        created.append(context.relative_to(root).as_posix())
    docs_root.mkdir(parents=True, exist_ok=True)
    if not docs_index.exists():
        docs_index.write_text(template_path("docs-index.md").read_text(encoding="utf-8"), encoding="utf-8")
        created.append(docs_index.relative_to(root).as_posix())
    return created


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def enable(root: Path, allow_feature_branch: bool = False, allow_dirty: bool = False) -> dict[str, Any]:
    existing = load_config(root)
    if existing is not None and existing.get("status") == "enabled":
        created = ensure_base_docs(root, existing)
        projection = render_agent_entries(root, existing, write=False)
        return {
            "status": "enabled",
            "already_enabled": True,
            "config": CONFIG_NAME,
            "created": created,
            "maturity": existing.get("maturity", "bootstrapping"),
            "doccanon_version": existing.get("doccanon_version"),
            "agent_entry": projection,
        }
    branch = branch_context(root)
    if branch["kind"] == "feature" and not allow_feature_branch:
        raise DocCanonError(
            f"Refusing repository-wide initialization on feature branch {branch['current_branch']}; "
            "use the integration branch or pass --allow-feature-branch explicitly"
        )
    if branch["dirty"] and not allow_dirty:
        raise DocCanonError("Refusing initialization in a dirty worktree; isolate or finish existing work, or pass --allow-dirty explicitly")
    config = {
        "status": "enabled",
        "doccanon_version": skill_version(),
        "maturity": "bootstrapping",
        "docs_root": "docs",
        "context_file": "CONTEXT.md",
        "required_domains": [],
        "registry": DEFAULT_REGISTRY,
        "archive_root": DEFAULT_ARCHIVE_ROOT,
        "agent_entry": DEFAULT_AGENT_ENTRY,
        "agent_adapters": list(DEFAULT_AGENT_ADAPTERS),
        "integration_branch": branch["integration_branch"],
        "release_branches": branch["release_branches"],
        "development_log_root": "docs/development",
        "release_log_root": "docs/releases",
        "decided_at": now_iso(),
    }
    write_config(root, config)
    created = ensure_base_docs(root, config)
    projected = render_agent_entries(root, config, write=True)
    created.extend(item["path"] for item in projected["files"] if item["changed"])
    registry = build_registry(root, config)
    return {
        "status": "enabled",
        "config": CONFIG_NAME,
        "created": created,
        "branch": branch,
        "agent_entry": projected,
        "registry": registry,
    }


