@dataclass
class DocumentRecord:
    path: Path
    relative: str
    authority: str
    covers: list[str]
    domains: list[str]
    verified_at: str | None
    plan_status: str | None = None
    plan_target: str | None = None


def document_records(root: Path, config: dict[str, Any]) -> list[DocumentRecord]:
    records: list[DocumentRecord] = []
    for path in markdown_files(root, config):
        rel = path.relative_to(root).as_posix()
        meta = frontmatter(path.read_text(encoding="utf-8", errors="replace"))
        covers = meta.get("doccanon_covers", [])
        domains = meta.get("doccanon_domains", [])
        if isinstance(covers, str):
            covers = [covers]
        if isinstance(domains, str):
            domains = [domains]
        plan_status = meta.get("doccanon_status")
        plan_target = meta.get("doccanon_target")
        records.append(
            DocumentRecord(
                path=path,
                relative=rel,
                authority=str(meta.get("doccanon_authority", "unclassified")),
                covers=[str(item) for item in covers],
                domains=[str(item) for item in domains],
                verified_at=str(meta["doccanon_verified_at"]) if meta.get("doccanon_verified_at") else None,
                plan_status=str(plan_status) if plan_status is not None else None,
                plan_target=str(plan_target) if plan_target is not None else None,
            )
        )
    return records


def normalize_relative_path(value: str, label: str) -> str:
    stripped = value.strip()
    if not stripped:
        raise DocCanonError(f"{label} must name a project-relative file")
    candidate = Path(stripped)
    if candidate.is_absolute() or ".." in candidate.parts:
        raise DocCanonError(f"{label} must stay inside the project")
    return candidate.as_posix()


def agent_entry_targets(config: dict[str, Any]) -> list[tuple[str, str]]:
    entry = str(config.get("agent_entry", DEFAULT_AGENT_ENTRY)).strip()
    if not entry:
        return []
    targets: list[tuple[str, str]] = [(normalize_relative_path(entry, "agent_entry"), "entry")]
    for adapter in config_list(config, "agent_adapters", list(DEFAULT_AGENT_ADAPTERS)):
        filename = AGENT_ADAPTER_FILES.get(adapter)
        if not filename:
            continue
        if all(path != filename for path, _ in targets):
            targets.append((filename, "adapter"))
    return targets


def doccanon_artifact_paths(config: dict[str, Any]) -> set[str]:
    paths = {relative for relative, _ in agent_entry_targets(config)}
    paths.update({".ignore", ".rgignore"})
    registry = str(config.get("registry", "")).strip()
    if registry:
        paths.add(normalize_relative_path(registry, "registry"))
    return paths


def registry_rel(config: dict[str, Any]) -> str:
    value = str(config.get("registry", "")).strip() or DEFAULT_REGISTRY
    return normalize_relative_path(value, "registry").rstrip("/")


def registry_path(root: Path, config: dict[str, Any]) -> Path:
    return (root / registry_rel(config)).resolve()


def registry_entries(
    root: Path,
    config: dict[str, Any],
    records: list[DocumentRecord] | None = None,
) -> list[dict[str, Any]]:
    archive_rel = archive_root_relative(config)
    archive_prefix = archive_rel + "/" if archive_rel else None
    entries: list[dict[str, Any]] = []
    for record in records if records is not None else document_records(root, config):
        if record.authority not in CONTEXT_AUTHORITIES:
            continue
        if archive_prefix and (record.relative == archive_rel or record.relative.startswith(archive_prefix)):
            continue
        entries.append(
            {
                "document": record.relative,
                "authority": record.authority,
                "domains": sorted(record.domains),
                "covers": sorted(record.covers),
                "verified_at": record.verified_at,
            }
        )
    entries.sort(key=lambda item: item["document"])
    return entries


def read_registry(root: Path, config: dict[str, Any]) -> dict[str, Any] | None:
    path = registry_path(root, config)
    if not path.is_file():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DocCanonError(f"Invalid canonical registry: {exc}") from exc
    if not isinstance(payload, dict) or not isinstance(payload.get("entries"), list):
        raise DocCanonError("Invalid canonical registry: entries must be an array")
    return payload


def registry_findings(
    root: Path,
    config: dict[str, Any],
    records: list[DocumentRecord],
) -> list[Finding]:
    payload = read_registry(root, config)
    if payload is None:
        return [
            Finding(
                "error",
                "missing-registry",
                "Owner registry is missing; run registry build",
                registry_rel(config),
            )
        ]
    expected = {entry["document"]: entry for entry in registry_entries(root, config, records)}
    actual: dict[str, dict[str, Any]] = {}
    for entry in payload.get("entries", []):
        if isinstance(entry, dict) and str(entry.get("document", "")).strip():
            actual[str(entry["document"])] = entry
    fields = ("authority", "domains", "covers", "verified_at")
    findings: list[Finding] = []
    for document in sorted(set(expected) - set(actual)):
        findings.append(
            Finding(
                "error",
                "unregistered-owner",
                "Active authority document is not in the owner registry; run registry build",
                document,
            )
        )
    for document in sorted(set(actual) - set(expected)):
        findings.append(
            Finding(
                "error",
                "stale-registry-entry",
                "Owner registry entry has no active document; run registry build",
                document,
            )
        )
    for document in sorted(set(expected) & set(actual)):
        expected_fields = {field: expected[document].get(field) for field in fields}
        actual_fields = {field: actual[document].get(field) for field in fields}
        if expected_fields != actual_fields:
            findings.append(
                Finding(
                    "error",
                    "registry-entry-outdated",
                    "Owner registry entry is out of date; run registry build",
                    document,
                )
            )
    return findings


def registry_report(
    root: Path,
    config: dict[str, Any],
    records: list[DocumentRecord] | None = None,
) -> tuple[dict[str, Any], list[Finding]]:
    if not str(config.get("registry", "")).strip():
        return {"status": "not-configured", "registry": None, "entry_count": 0, "finding_count": 0}, []
    records = records if records is not None else document_records(root, config)
    findings = registry_findings(root, config, records)
    payload = read_registry(root, config)
    status = "missing" if payload is None else ("consistent" if not findings else "drift")
    return (
        {
            "status": status,
            "registry": registry_rel(config),
            "entry_count": len(payload.get("entries", [])) if payload else 0,
            "finding_count": len(findings),
        },
        findings,
    )


def registry_needs_build(
    root: Path,
    config: dict[str, Any],
    records: list[DocumentRecord] | None = None,
) -> bool:
    if not str(config.get("registry", "")).strip():
        return True
    summary, _ = registry_report(root, config, records)
    return summary["status"] in {"missing", "drift"}


def build_registry(root: Path, config: dict[str, Any] | None = None) -> dict[str, Any]:
    config = config or load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("registry requires an enabled DocCanon project")
    path = registry_path(root, config)
    payload = {
        "schema_version": 1,
        "source_revision": git_head(root),
        "entries": registry_entries(root, config),
    }
    rendered = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    if not path.is_file() or path.read_text(encoding="utf-8") != rendered:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered, encoding="utf-8")
    return {
        "status": "built",
        "registry": path.relative_to(root).as_posix(),
        "entry_count": len(payload["entries"]),
    }


def is_repo_meta(relative: str) -> bool:
    normalized = relative.replace(os.sep, "/")
    if "/" in normalized:
        return False
    lower = normalized.lower()
    if lower in REPO_META_FILES:
        return True
    stem = re.split(r"[._]", lower, maxsplit=1)[0]
    return stem in REPO_META_STEMS


def entry_routing_rows(root: Path, config: dict[str, Any]) -> list[tuple[str, str]]:
    docs_root = str(config.get("docs_root", "docs")).strip("/")
    prefix = docs_root + "/"
    groups: dict[str, list[str]] = {}
    for record in document_records(root, config):
        if record.authority not in CONTEXT_AUTHORITIES:
            continue
        if not record.relative.startswith(prefix):
            continue
        rest = record.relative[len(prefix):]
        category = rest.split("/", 1)[0] if "/" in rest else ""
        groups.setdefault(category, []).append(record.relative)
    ordered = [category for category in ENTRY_CATEGORY_ORDER if category in groups]
    ordered.extend(sorted(category for category in groups if category not in ENTRY_CATEGORY_ORDER))
    rows: list[tuple[str, str]] = []
    for category in ordered:
        if category:
            readme = f"{docs_root}/{category}/README.md"
            label = ENTRY_CATEGORY_LABELS.get(category, category.replace("-", " ").replace("_", " ").title())
        else:
            readme = f"{docs_root}/README.md"
            label = "General"
        paths = [path for path in sorted(groups[category]) if path != readme]
        if not paths:
            continue
        if category and readme in groups[category]:
            rows.append((label, f"`{readme}`"))
            continue
        shown = paths[:3]
        value = ", ".join(f"`{path}`" for path in shown)
        if len(paths) > len(shown):
            value += f" (+{len(paths) - len(shown)} more via `{docs_root}/README.md`)"
        rows.append((label, value))
    return rows


def entry_projection(root: Path, config: dict[str, Any], kind: str) -> str:
    context_file = str(config.get("context_file", "CONTEXT.md"))
    docs_root = str(config.get("docs_root", "docs")).strip("/")
    if kind == "adapter":
        entry = agent_entry_targets(config)[0][0]
        return (
            "<!-- Generated by DocCanon. Imports the shared agent entry. "
            "Do not edit outside the custom section. -->\n"
            f"@{entry}\n"
        )
    lines = [
        "<!-- Generated by DocCanon from the canonical library. Do not edit outside the custom section. -->",
        "",
        "# Coding agent entry",
        "",
        "This file is a generated projection of the project's governed knowledge. It owns no facts.",
        f"Durable knowledge lives in `{context_file}` and `{docs_root}/`; code, tests, configuration, and",
        "runtime evidence remain the proof of current behavior.",
        "",
        "## Task context protocol",
        "",
        "Before substantive work, load only the smallest canonical context relevant to the task, then inspect",
        "the code needed to verify or implement it. If the DocCanon skill is available, follow its task loop.",
        f"Otherwise, read `{context_file}` and `{docs_root}/README.md`, follow the owning area, and never",
        "treat retired material as current behavior.",
        "",
        "## Retrieval policy",
        "",
        "- A document is current state only when its frontmatter declares `doccanon_authority:`",
        "  `current-state`, `human-confirmed`, `append-only`, or `generated`.",
        "- `snapshot`, `historical`, `superseded`, `draft`, and `unclassified` documents are history or",
        "  unverified material. Use them only for archaeology, never as current behavior.",
        "- `plan` documents describe intended future work. Use them for planning and launch readiness,",
        "  never as current behavior.",
        f"- `{docs_root}/development/` and `{docs_root}/releases/` are historical snapshots.",
    ]
    archive_rel = archive_root_relative(config)
    if archive_rel:
        lines.append(
            f"- Retired material is archived under `{archive_rel}/` and excluded from default search. "
            "Consult it only for archaeology."
        )
    manifest = config.get("migration_manifest")
    if manifest:
        lines.append(f"- Frozen legacy sources and their evidence: `{manifest}`.")
    lines.extend(
        [
            "",
            "## Where to read first",
            "",
            "| Area | Canonical owner |",
            "| --- | --- |",
            f"| Canonical terminology and domain boundaries | `{context_file}` |",
        ]
    )
    rows = entry_routing_rows(root, config)
    for label, value in rows[:ENTRY_ROUTING_ROW_LIMIT]:
        lines.append(f"| {label} | {value} |")
    if len(rows) > ENTRY_ROUTING_ROW_LIMIT:
        lines.append(f"| More areas | `{docs_root}/README.md` |")
    lines.append(f"| Documentation map | `{docs_root}/README.md` |")
    return "\n".join(lines) + "\n"


def extract_custom_section(text: str, label: str) -> str:
    start = text.find(ENTRY_CUSTOM_START)
    end = text.find(ENTRY_CUSTOM_END)
    if start < 0 and end < 0:
        return text.strip("\n")
    if start < 0 or end < 0 or end < start:
        raise DocCanonError(
            f"{label} has an incomplete DocCanon custom section; keep both markers as a pair"
        )
    return text[start + len(ENTRY_CUSTOM_START):end].strip("\n")


def custom_section(body: str) -> str:
    body = body.strip("\n")
    if not body:
        return f"{ENTRY_CUSTOM_START}\n{ENTRY_CUSTOM_END}\n"
    return f"{ENTRY_CUSTOM_START}\n{body}\n{ENTRY_CUSTOM_END}\n"


def compose_agent_entry(existing: str | None, projection: str, kind: str, label: str) -> str:
    if existing is None:
        custom = DEFAULT_CUSTOM_HINT
    else:
        custom = extract_custom_section(existing, label)
    heading = "## Tool-specific notes (user-owned)" if kind == "adapter" else "## Project-specific notes (user-owned)"
    return projection.rstrip() + "\n\n" + heading + "\n\n" + custom_section(custom)


def is_generated_entry(text: str) -> bool:
    return GENERATED_ENTRY_MARKER in text


def render_agent_entries(root: Path, config: dict[str, Any], write: bool, allow_adoption: bool = True) -> dict[str, Any]:
    files: list[dict[str, Any]] = []
    changed_any = False
    for relative, kind in agent_entry_targets(config):
        path = (root / relative).resolve()
        try:
            path.relative_to(root)
        except ValueError as exc:
            raise DocCanonError(f"Agent entry must stay inside the project: {relative}") from exc
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        legacy = existing is not None and not is_generated_entry(existing)
        rendered = compose_agent_entry(existing, entry_projection(root, config, kind), kind, relative)
        changed = existing != rendered
        adopted = False
        blocked_legacy = False
        if changed:
            changed_any = True
            if write and legacy and not allow_adoption:
                blocked_legacy = True
            elif write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(rendered, encoding="utf-8")
                adopted = legacy
        files.append(
            {
                "path": relative,
                "kind": kind,
                "exists": existing is not None,
                "changed": changed,
                "legacy": legacy,
                "adopted": adopted,
                "blocked_legacy": blocked_legacy,
            }
        )
    if write:
        if any(item["blocked_legacy"] for item in files):
            status = "blocked"
        else:
            status = "rendered" if changed_any else "current"
    else:
        status = "drift" if changed_any else "current"
    return {"status": status, "files": files}


def render_command(root: Path, check: bool) -> tuple[dict[str, Any], int]:
    config = load_config(root)
    if config is None:
        return {"status": "unconfigured", "project": str(root), "files": []}, 0
    if config["status"] == "disabled":
        return {"status": "disabled", "project": str(root), "files": []}, 0
    result = render_agent_entries(root, config, write=not check)
    result["project"] = str(root)
    result["check"] = check
    return result, 1 if result["status"] == "drift" else 0


def archive_root_relative(config: dict[str, Any]) -> str:
    value = str(config.get("archive_root", DEFAULT_ARCHIVE_ROOT)).strip()
    if not value:
        return ""
    return normalize_relative_path(value, "archive_root").rstrip("/")


def search_ignore_file(root: Path, archive_rel: str) -> str | None:
    if not archive_rel:
        return None
    patterns = {
        archive_rel,
        archive_rel + "/",
        "/" + archive_rel,
        "/" + archive_rel + "/",
    }
    for name in (".ignore", ".rgignore", ".gitignore"):
        path = root / name
        if not path.is_file():
            continue
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            stripped = line.strip()
            if stripped and not stripped.startswith("#") and stripped in patterns:
                return name
    return None


def search_ignore_covers(root: Path, archive_rel: str) -> bool:
    return search_ignore_file(root, archive_rel) is not None


def ensure_search_ignore(root: Path, config: dict[str, Any]) -> dict[str, Any]:
    archive_rel = archive_root_relative(config)
    if not archive_rel:
        return {"updated": False, "file": None, "pattern": None}
    pattern = archive_rel + "/"
    covering = search_ignore_file(root, archive_rel)
    if covering:
        return {"updated": False, "file": covering, "pattern": pattern}
    path = root / ".ignore"
    existing = path.read_text(encoding="utf-8", errors="replace") if path.is_file() else ""
    separator = "" if not existing or existing.endswith("\n") else "\n"
    path.write_text(existing + separator + pattern + "\n", encoding="utf-8")
    return {"updated": True, "file": ".ignore", "pattern": pattern}


def with_retired_notice(text: str, notice: str) -> str:
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end >= 0:
            return text[: end + 5] + "\n" + notice + "\n\n" + text[end + 5 :].lstrip("\n")
    return notice + "\n\n" + text


def append_archive_index(
    root: Path,
    config: dict[str, Any],
    target_rel: str,
    disposition: str,
    reason: str,
) -> dict[str, Any]:
    archive_rel = archive_root_relative(config)
    if not archive_rel:
        return {"status": "skipped", "path": None}
    index = root / archive_rel / "README.md"
    marker = f"<!-- doccanon-archived: {target_rel} -->"
    if index.is_file() and marker in index.read_text(encoding="utf-8", errors="replace"):
        return {"status": "already-recorded", "path": index.relative_to(root).as_posix()}
    if not index.exists():
        index.parent.mkdir(parents=True, exist_ok=True)
        index.write_text(
            "---\ndoccanon_authority: historical\n---\n\n"
            "# Archive\n\n"
            "Frozen, non-current material retained for provenance. Read only for archaeology; "
            "never treat it as current truth.\n\n"
            "| Document | Disposition | Reason | Retired at |\n|---|---|---|---|\n",
            encoding="utf-8",
        )
    revision = (git_head(root) or "unknown")[:12]
    row = f"| {marker} `{target_rel}` | {disposition} | {reason or '-'} | {now_iso()} `{revision}` |\n"
    with index.open("a", encoding="utf-8") as handle:
        handle.write(row)
    return {"status": "recorded", "path": index.relative_to(root).as_posix()}


def retire_feature_link(
    root: Path,
    config: dict[str, Any],
    feature_id: str,
    document: str,
) -> dict[str, Any] | None:
    manifest_rel = str(config.get("feature_manifest", DEFAULT_FEATURE_MANIFEST))
    path = root / manifest_rel
    if not path.is_file():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DocCanonError(f"Invalid feature manifest: {exc}") from exc
    changed = False
    for feature in payload.get("features", []):
        if isinstance(feature, dict) and str(feature.get("id", "")) == feature_id:
            feature["status"] = "retired"
            feature["document"] = document
            changed = True
            break
    if not changed:
        return None
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return {"feature": feature_id, "status": "retired", "document": document}


def retired_current_feature_docs(root: Path, config: dict[str, Any]) -> list[str]:
    manifest_rel = str(config.get("feature_manifest", DEFAULT_FEATURE_MANIFEST))
    path = root / manifest_rel
    if not path.is_file():
        return []
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DocCanonError(f"Invalid feature manifest: {exc}") from exc
    archive_rel = archive_root_relative(config)
    archive_prefix = archive_rel + "/" if archive_rel else None
    documents: list[str] = []
    for feature in payload.get("features", []):
        if not isinstance(feature, dict) or feature.get("status") != "retired":
            continue
        document = str(feature.get("document", "")).strip()
        if not document:
            continue
        resolved = (root / document).resolve()
        try:
            relative = resolved.relative_to(root).as_posix()
        except ValueError:
            continue
        if archive_prefix and (relative == archive_rel or relative.startswith(archive_prefix)):
            continue
        if not resolved.is_file():
            continue
        authority = str(frontmatter(resolved.read_text(encoding="utf-8", errors="replace")).get("doccanon_authority", "unclassified"))
        if authority in CONTEXT_AUTHORITIES:
            documents.append(relative)
    return sorted(documents)


def retire_document(
    root: Path,
    document: str,
    reason: str,
    owner: str | None,
    disposition: str,
    pointer: bool,
    allow_active: bool = False,
) -> dict[str, Any]:
    config = load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("retire requires an enabled DocCanon project")
    archive_rel = archive_root_relative(config)
    if not archive_rel:
        raise DocCanonError("archive_root is disabled in .doccanon.yml")
    if disposition not in RETIRE_AUTHORITIES:
        raise DocCanonError("disposition must be historical or superseded")
    stamp = disposition
    source = (root / document).resolve()
    try:
        source.relative_to(root)
    except ValueError as exc:
        raise DocCanonError("Document must stay inside the project") from exc
    if not source.is_file():
        raise DocCanonError(f"Document not found: {document}")
    relative = source.relative_to(root).as_posix()
    if relative == archive_rel or relative.startswith(archive_rel + "/"):
        raise DocCanonError("Document is already in the archive")
    protected = {CONFIG_NAME, str(config.get("context_file", "CONTEXT.md"))}
    protected.update(target for target, _ in agent_entry_targets(config))
    if relative in protected:
        raise DocCanonError(f"{relative} is managed by DocCanon and cannot be retired")
    text = source.read_text(encoding="utf-8", errors="replace")
    authority = str(frontmatter(text).get("doccanon_authority", "unclassified"))
    if authority in CONTEXT_AUTHORITIES and not allow_active:
        raise DocCanonError(
            f"{relative} still has active authority {authority!r}; update or remove its canonical ownership first"
        )
    target = root / archive_rel / relative
    if target.exists():
        raise DocCanonError(f"Archive target already exists: {target.relative_to(root).as_posix()}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    markdown_like = target.suffix.lower() in {".md", ".mdx", ".markdown"}
    if markdown_like:
        values: dict[str, Any] = {"doccanon_authority": stamp, "doccanon_retired_from": relative}
        if owner:
            values["doccanon_owner"] = owner.strip()
        update_frontmatter(target, values)
    notice_lines = [
        "> **Retired by DocCanon.** This document is provenance, not current truth.",
        f"> Archived from `{relative}` on {now_iso()[:10]}.",
    ]
    if owner:
        notice_lines.append(f"> Canonical owner: `{owner.strip()}`.")
    if reason:
        notice_lines.append(f"> Reason: {reason.strip()}")
    target.write_text(
        with_retired_notice(target.read_text(encoding="utf-8"), "\n".join(notice_lines)),
        encoding="utf-8",
    )
    archived_to = target.relative_to(root).as_posix()
    pointer_path = None
    if pointer:
        stub = ["# Moved"]
        if owner:
            stub.append(f"Canonical owner: `{owner.strip()}`")
        stub.extend(
            [
                "",
                f"> This document moved to the DocCanon archive: `{archived_to}`.",
                "> It is provenance, not current truth.",
            ]
        )
        source.write_text("\n".join(stub) + "\n", encoding="utf-8")
        if markdown_like:
            stub_values: dict[str, Any] = {"doccanon_authority": stamp, "doccanon_archived_to": archived_to}
            if owner:
                stub_values["doccanon_owner"] = owner.strip()
            update_frontmatter(source, stub_values)
        pointer_path = relative
    else:
        source.unlink()
    feature_update = None
    feature_id = str(frontmatter(text).get("doccanon_feature", "")).strip()
    if feature_id:
        feature_update = retire_feature_link(root, config, feature_id, archived_to)
    index = append_archive_index(root, config, archived_to, stamp, reason)
    registry = None
    if str(config.get("registry", "")).strip() and registry_path(root, config).is_file():
        registry = build_registry(root, config)
    return {
        "status": "retired",
        "document": relative,
        "archived_to": archived_to,
        "authority": stamp,
        "disposition": disposition,
        "pointer": pointer_path,
        "owner": owner.strip() if owner else None,
        "feature": feature_update,
        "archive_index": index,
        "registry": registry,
        "search_ignore": ensure_search_ignore(root, config),
    }


def upgrade_report(root: Path) -> dict[str, Any]:
    install = install_provenance()
    config = load_config(root)
    if config is None:
        return {"status": "unconfigured", "project": str(root), "install": install}
    if config["status"] == "disabled":
        return {"status": "disabled", "project": str(root), "install": install}
    skill = skill_version()
    project_version = str(config.get("doccanon_version", "")).strip() or None
    steps: list[dict[str, Any]] = []
    legacy_keys = sorted(key for key in UPGRADE_LEGACY_KEYS if key in config)
    if legacy_keys:
        steps.append(
            {
                "id": "config-cleanup",
                "kind": "mechanical",
                "description": "Remove retired configuration fields: " + ", ".join(legacy_keys),
            }
        )
    projection = render_agent_entries(root, config, write=False)
    legacy_entries = [
        item["path"] for item in projection["files"] if item.get("legacy") and item["changed"]
    ]
    if legacy_entries:
        steps.append(
            {
                "id": "legacy-agent-entry",
                "kind": "semantic",
                "description": "Hand-written agent entries predate the generated projection; absorb durable "
                'rules into canonical owners, then run render (or opt out with agent_entry: "")',
                "paths": legacy_entries,
            }
        )
    manifest = config.get("migration_manifest")
    if manifest:
        report = migration_manifest_status(root, str(manifest))
        if report.get("sources_in_tree_count"):
            steps.append(
                {
                    "id": "frozen-sources-in-tree",
                    "kind": "semantic",
                    "description": f"{report['sources_in_tree_count']} non-integrated migration source(s) still "
                    "live in the searchable tree; review each and retire it, absorb it into a canonical "
                    "owner, or keep it as a canonical document",
                }
            )
        if report.get("missing_source_count"):
            steps.append(
                {
                    "id": "missing-manifest-sources",
                    "kind": "info",
                    "description": f"{report['missing_source_count']} migration manifest source(s) no longer "
                    "exist; provenance relies on Git history or removed material",
                }
            )
    records = document_records(root, config)
    unknown = sorted(
        {record.authority for record in records if record.authority not in DECLARED_AUTHORITIES}
    )
    if unknown:
        steps.append(
            {
                "id": "unknown-authorities",
                "kind": "semantic",
                "description": "Classify unknown doccanon_authority values: " + ", ".join(unknown)
                + "; accepted decisions use append-only, future work uses plan",
            }
        )
    docs_root = str(config.get("docs_root", "docs")).strip("/")
    decisions = [
        record.relative
        for record in records
        if record.relative.startswith(docs_root + "/adr/") and record.authority == "unclassified"
    ]
    if decisions:
        steps.append(
            {
                "id": "unclassified-decision-record",
                "kind": "semantic",
                "description": f"{len(decisions)} decision record(s) declare no authority; accepted decisions "
                "use doccanon_authority: append-only",
                "paths": decisions[:10],
            }
        )
    if registry_needs_build(root, config, records):
        steps.append(
            {
                "id": "registry-index",
                "kind": "mechanical",
                "description": "Owner registry is missing or out of date; upgrade apply builds it",
            }
        )
    retired_contracts = retired_current_feature_docs(root, config)
    if retired_contracts:
        steps.append(
            {
                "id": "retired-feature-contract",
                "kind": "mechanical",
                "description": f"{len(retired_contracts)} retired feature(s) still keep an active contract; "
                "upgrade apply archives them",
                "paths": retired_contracts[:10],
            }
        )
    configured = set(config_list(config, "agent_adapters", list(DEFAULT_AGENT_ADAPTERS)))
    for adapter, filename in sorted(AGENT_ADAPTER_FILES.items()):
        if adapter in configured:
            continue
        path = root / filename
        if path.is_file() and not is_generated_entry(path.read_text(encoding="utf-8", errors="replace")):
            steps.append(
                {
                    "id": "unmanaged-agent-adapter",
                    "kind": "info",
                    "description": f"{filename} is hand-maintained but the {adapter} adapter is not configured; "
                    "add it to agent_adapters and run render, or remove the file",
                    "paths": [filename],
                }
            )
    open_steps = [step for step in steps if step["kind"] in {"mechanical", "semantic"}]
    version_pending = project_version != skill
    return {
        "status": "required" if version_pending or open_steps else "current",
        "project": str(root),
        "project_version": project_version,
        "skill_version": skill,
        "stamp_pending": version_pending,
        "steps": steps,
        "install": install,
    }


def upgrade_apply(root: Path) -> dict[str, Any]:
    report = upgrade_report(root)
    if report["status"] in {"unconfigured", "disabled"}:
        raise DocCanonError("upgrade requires an enabled DocCanon project")
    config = load_config(root)
    if config is None:
        raise DocCanonError("upgrade requires an enabled DocCanon project")
    legacy_keys = [key for key in UPGRADE_LEGACY_KEYS if key in config]
    for key in legacy_keys:
        config.pop(key, None)
    applied = ["config-cleanup"] if legacy_keys else []
    if report["status"] == "current" and not legacy_keys:
        return {
            "status": "current",
            "project": str(root),
            "project_version": report["project_version"],
            "skill_version": report["skill_version"],
            "applied": [],
            "pending_steps": [],
            "install": report.get("install"),
        }
    archived_contracts: list[dict[str, Any]] = []
    for document in retired_current_feature_docs(root, config):
        result = retire_document(
            root,
            document,
            "Feature was already marked retired; archived while adopting the DocCanon contract",
            None,
            "historical",
            False,
            allow_active=True,
        )
        archived_contracts.append({"document": document, "archived_to": result.get("archived_to")})
    if archived_contracts:
        applied.append("retired-feature-contract")
    if not str(config.get("registry", "")).strip():
        config["registry"] = DEFAULT_REGISTRY
    if registry_needs_build(root, config, document_records(root, config)):
        build_registry(root, config)
        applied.append("registry-index")
    pending = [step for step in report["steps"] if step["kind"] == "semantic"]
    if pending:
        write_config(root, config)
        return {
            "status": "in-progress",
            "project": str(root),
            "project_version": report["project_version"],
            "skill_version": report["skill_version"],
            "applied": applied,
            "pending_steps": pending,
            "archived_contracts": archived_contracts,
            "next": "Resolve every pending step, then rerun upgrade apply. See references/upgrading.md.",
            "install": report.get("install"),
        }
    config["doccanon_version"] = report["skill_version"]
    write_config(root, config)
    return {
        "status": "applied",
        "project": str(root),
        "project_version": report["skill_version"],
        "skill_version": report["skill_version"],
        "applied": applied + ["version-stamp"],
        "pending_steps": [step for step in report["steps"] if step["kind"] == "info"],
        "archived_contracts": archived_contracts,
        "install": report.get("install"),
    }


def revision_exists(root: Path, revision: str) -> bool:
    result = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--verify", f"{revision}^{{commit}}"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    return result.returncode == 0


def migration_manifest_status(root: Path, manifest: str) -> dict[str, Any]:
    path = (root / manifest).resolve()
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise DocCanonError("Migration manifest must be inside the project") from exc
    config = load_config(root)
    archive_rel = archive_root_relative(config) if config else DEFAULT_ARCHIVE_ROOT
    if not path.is_file():
        return {
            "status": "missing",
            "manifest": manifest,
            "candidate_count": 0,
            "mapped_count": 0,
            "integrated_count": 0,
            "residual_claim_count": 0,
            "unresolved_count": 0,
            "missing_source_count": 0,
            "sources_in_tree_count": 0,
            "findings": ["migration manifest does not exist"],
        }
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DocCanonError(f"Invalid migration manifest: {exc}") from exc
    entries = payload.get("entries", [])
    if not isinstance(entries, list):
        raise DocCanonError("Migration manifest entries must be an array")
    schema_version = payload.get("schema_version")
    candidate_count = int(payload.get("candidate_count", len(entries)))
    if schema_version != 2:
        findings = [
            f"migration manifest schema_version must be 2; version {schema_version!r} records mapping but does not prove canonical integration"
        ]
        if candidate_count != len(entries):
            findings.append(f"candidate_count is {candidate_count}, but manifest has {len(entries)} entries")
        return {
            "status": "incomplete",
            "manifest": path.relative_to(root).as_posix(),
            "candidate_count": candidate_count,
            "mapped_count": len(entries),
            "integrated_count": 0,
            "residual_claim_count": 0,
            "unresolved_count": max(candidate_count, len(entries)),
            "missing_source_count": 0,
            "sources_in_tree_count": 0,
            "findings": findings,
        }
    findings: list[str] = []
    sources: set[str] = set()
    unresolved = 0
    integrated_count = 0
    residual_count = 0
    missing_sources = 0
    sources_in_tree = 0
    required = {
        "source",
        "classification",
        "action",
        "status",
        "confidence",
        "evidence",
        "conflicts",
        "requires_review",
    }
    terminal = {"integrated", "historical", "superseded", "ignored", "archived"}
    integration_actions = {"adopt", "move", "merge", "split"}
    retirement_actions = {"archive", "supersede", "ignore"}
    integrated_dispositions = {"canonical", "superseded", "archived"}

    def target_headings(target: Path) -> set[str]:
        text = target.read_text(encoding="utf-8", errors="replace")
        return {
            match.group(1).strip()
            for match in re.finditer(r"^#{1,6}\s+(.+?)\s*$", text, flags=re.MULTILINE)
        }

    for index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            findings.append(f"entry {index} must be an object")
            unresolved += 1
            continue
        missing = sorted(required - set(entry))
        if missing:
            findings.append(f"entry {index} missing: {', '.join(missing)}")
        source = str(entry.get("source", ""))
        if source in sources:
            findings.append(f"duplicate source: {source}")
        sources.add(source)
        entry_unresolved = bool(missing)
        status = entry.get("status")
        action = entry.get("action")
        conflicts = entry.get("conflicts")
        evidence = entry.get("evidence")
        if status not in terminal:
            entry_unresolved = True
        if entry.get("requires_review") is True:
            entry_unresolved = True
        if not isinstance(conflicts, list):
            findings.append(f"entry {index} conflicts must be an array")
            entry_unresolved = True
        elif conflicts:
            findings.append(f"entry {index} has unresolved conflicts")
            entry_unresolved = True
        if not isinstance(evidence, list) or not evidence or not all(
            isinstance(item, str) and item.strip() for item in evidence
        ):
            findings.append(f"entry {index} must record evidence for its disposition")
            entry_unresolved = True

        if status == "integrated":
            integrated_count += 1
            if action not in integration_actions:
                findings.append(f"entry {index} integrated status requires adopt, move, merge, or split")
                entry_unresolved = True
            integrations = entry.get("integrations")
            verification = entry.get("verification")
            residual = entry.get("residual_claims")
            disposition = entry.get("source_disposition")
            if not isinstance(integrations, list) or not integrations:
                findings.append(f"entry {index} must include at least one canonical integration receipt")
                entry_unresolved = True
            else:
                for receipt_index, receipt in enumerate(integrations):
                    label = f"entry {index} integration {receipt_index}"
                    if not isinstance(receipt, dict):
                        findings.append(f"{label} must be an object")
                        entry_unresolved = True
                        continue
                    target_name = receipt.get("target")
                    sections = receipt.get("sections")
                    claims = receipt.get("absorbed_claims")
                    if not isinstance(target_name, str) or not target_name:
                        findings.append(f"{label} missing target")
                        entry_unresolved = True
                    else:
                        target = (root / target_name).resolve()
                        try:
                            target.relative_to(root)
                        except ValueError:
                            findings.append(f"{label} target must be inside the project")
                            entry_unresolved = True
                        else:
                            if not target.is_file():
                                findings.append(f"{label} target does not exist: {target_name}")
                                entry_unresolved = True
                            elif isinstance(sections, list) and sections:
                                headings = target_headings(target)
                                missing_sections = [section for section in sections if section not in headings]
                                if missing_sections:
                                    findings.append(
                                        f"{label} target is missing sections: {', '.join(str(item) for item in missing_sections)}"
                                    )
                                    entry_unresolved = True
                    if not isinstance(sections, list) or not sections or not all(isinstance(item, str) and item for item in sections):
                        findings.append(f"{label} must name canonical target sections")
                        entry_unresolved = True
                    if not isinstance(claims, list) or not claims or not all(isinstance(item, str) and item.strip() for item in claims):
                        findings.append(f"{label} must record absorbed claims")
                        entry_unresolved = True
            if not isinstance(verification, list) or not verification or not all(
                isinstance(item, str) and item.strip() for item in verification
            ):
                findings.append(f"entry {index} must record verification evidence for integrated claims")
                entry_unresolved = True
            if not isinstance(residual, list):
                findings.append(f"entry {index} residual_claims must be an array")
                entry_unresolved = True
            elif residual:
                residual_count += len(residual)
                findings.append(f"entry {index} still has {len(residual)} residual claim(s)")
                entry_unresolved = True
            if disposition not in integrated_dispositions:
                findings.append(f"entry {index} must retire the legacy source or declare it canonical")
                entry_unresolved = True
            rejected = entry.get("rejected_claims", [])
            if not isinstance(rejected, list):
                findings.append(f"entry {index} rejected_claims must be an array")
                entry_unresolved = True
            else:
                for rejected_index, claim in enumerate(rejected):
                    label = f"entry {index} rejected claim {rejected_index}"
                    if not isinstance(claim, dict):
                        findings.append(f"{label} must be an object")
                        entry_unresolved = True
                        continue
                    if not isinstance(claim.get("claim"), str) or not claim["claim"].strip():
                        findings.append(f"{label} must name the rejected claim")
                        entry_unresolved = True
                    if not isinstance(claim.get("reason"), str) or not claim["reason"].strip():
                        findings.append(f"{label} must record a reason")
                        entry_unresolved = True
                    rejected_evidence = claim.get("evidence")
                    if not isinstance(rejected_evidence, list) or not rejected_evidence or not all(
                        isinstance(item, str) and item.strip() for item in rejected_evidence
                    ):
                        findings.append(f"{label} must record evidence")
                        entry_unresolved = True
        elif status in terminal:
            if action not in retirement_actions:
                findings.append(f"entry {index} non-integrated source requires archive, supersede, or ignore")
                entry_unresolved = True
            reason = entry.get("disposition_reason")
            if not isinstance(reason, str) or not reason.strip():
                findings.append(f"entry {index} non-integrated source requires a disposition_reason")
                entry_unresolved = True
            if source:
                if (root / source).is_file():
                    sources_in_tree += 1
                elif archive_rel and (root / archive_rel / source).is_file():
                    pass
                else:
                    missing_sources += 1

        if entry_unresolved:
            unresolved += 1
    if candidate_count != len(entries):
        findings.append(f"candidate_count is {candidate_count}, but manifest has {len(entries)} entries")
    status = "complete" if not findings and unresolved == 0 and candidate_count == len(entries) else "incomplete"
    return {
        "status": status,
        "manifest": path.relative_to(root).as_posix(),
        "candidate_count": candidate_count,
        "mapped_count": len(entries),
        "integrated_count": integrated_count,
        "residual_claim_count": residual_count,
        "unresolved_count": unresolved,
        "missing_source_count": missing_sources,
        "sources_in_tree_count": sources_in_tree,
        "findings": findings,
    }


def feature_manifest_status(root: Path, manifest: str) -> dict[str, Any]:
    path = (root / manifest).resolve()
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise DocCanonError("Feature manifest must be inside the project") from exc
    if not path.is_file():
        return {
            "status": "missing",
            "manifest": manifest,
            "feature_count": 0,
            "documented_count": 0,
            "unresolved_count": 0,
            "findings": ["feature manifest does not exist"],
        }
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DocCanonError(f"Invalid feature manifest: {exc}") from exc
    features = payload.get("features", [])
    if not isinstance(features, list):
        raise DocCanonError("Feature manifest features must be an array")
    findings: list[str] = []
    project_files = [path.relative_to(root).as_posix() for path in tracked_and_untracked_files(root)]
    identifiers: set[str] = set()
    documented = 0
    unresolved = 0
    for index, feature in enumerate(features):
        if not isinstance(feature, dict):
            findings.append(f"feature {index} must be an object")
            unresolved += 1
            continue
        identifier = str(feature.get("id", "")).strip()
        name = str(feature.get("name", "")).strip()
        state = str(feature.get("status", "review")).strip()
        if not identifier or not name:
            findings.append(f"feature {index} requires id and name")
            unresolved += 1
            continue
        if identifier in identifiers:
            findings.append(f"duplicate feature id: {identifier}")
            unresolved += 1
            continue
        identifiers.add(identifier)
        if state == "excluded":
            if not str(feature.get("reason", "")).strip():
                findings.append(f"excluded feature {identifier} requires a reason")
                unresolved += 1
            continue
        if state == "retired":
            retired_document = str(feature.get("document", "")).strip()
            if retired_document:
                retired_path = (root / retired_document).resolve()
                try:
                    retired_relative = retired_path.relative_to(root).as_posix()
                except ValueError:
                    retired_relative = ""
                if retired_relative and retired_path.is_file():
                    authority = str(
                        frontmatter(retired_path.read_text(encoding="utf-8", errors="replace")).get(
                            "doccanon_authority", "unclassified"
                        )
                    )
                    if authority in CONTEXT_AUTHORITIES:
                        findings.append(
                            f"feature {identifier} is retired but {retired_document} still declares "
                            f"authority {authority!r}; archive it with the upgrade pass or retire"
                        )
                        unresolved += 1
            continue
        if state != "current":
            findings.append(f"feature {identifier} has unresolved status: {state}")
            unresolved += 1
            continue
        document = str(feature.get("document", "")).strip()
        patterns = feature.get("code_patterns", [])
        if isinstance(patterns, str):
            patterns = [patterns]
        if not document or not patterns:
            findings.append(f"current feature {identifier} requires document and code_patterns")
            unresolved += 1
            continue
        document_path = (root / document).resolve()
        try:
            document_path.relative_to(root)
        except ValueError:
            findings.append(f"feature {identifier} document is outside the project")
            unresolved += 1
            continue
        if not document_path.is_file():
            findings.append(f"feature {identifier} document does not exist: {document}")
            unresolved += 1
            continue
        text = document_path.read_text(encoding="utf-8", errors="replace")
        meta = frontmatter(text)
        covers = meta.get("doccanon_covers", [])
        domains = meta.get("doccanon_domains", [])
        if isinstance(covers, str):
            covers = [covers]
        if isinstance(domains, str):
            domains = [domains]
        headings = {heading.strip().lower() for heading in re.findall(r"(?m)^##\s+(.+?)\s*$", text)}
        sections = markdown_sections(text)
        missing_sections = sorted(REQUIRED_FEATURE_SECTIONS - headings)
        problems: list[str] = []
        if meta.get("doccanon_authority") != "current-state":
            problems.append("authority must be current-state")
        if str(meta.get("doccanon_feature", "")) != identifier:
            problems.append("doccanon_feature must match manifest id")
        if "features" not in {str(item) for item in domains}:
            problems.append("doccanon_domains must include features")
        if not covers:
            problems.append("doccanon_covers is required")
        elif not set(str(item) for item in patterns).issubset({str(item) for item in covers}):
            problems.append("manifest code_patterns must also appear in doccanon_covers")
        unmatched_patterns = [
            str(pattern)
            for pattern in patterns
            if not any(fnmatch.fnmatchcase(candidate, str(pattern)) for candidate in project_files)
        ]
        if unmatched_patterns:
            problems.append("code_patterns match no project files: " + ", ".join(unmatched_patterns))
        anchor = str(meta.get("doccanon_verified_at", ""))
        if not anchor or not revision_exists(root, anchor):
            problems.append("doccanon_verified_at must reference a Git commit")
        elif not revision_is_ancestor(root, anchor):
            problems.append("doccanon_verified_at is not an ancestor of the current branch")
        if missing_sections:
            problems.append("missing sections: " + ", ".join(missing_sections))
        thin_sections = sorted(
            section for section in REQUIRED_FEATURE_SECTIONS
            if section in sections and len(re.sub(r"\s+", " ", sections[section]).strip()) < 20
        )
        if thin_sections:
            problems.append("sections are too thin: " + ", ".join(thin_sections))
        if len(re.sub(r"\s+", " ", sections.get("change guidance", "")).strip()) < 60:
            problems.append("Change guidance must identify coupled surfaces and failure risks")
        verification = sections.get("verification", "")
        if verification and not re.search(r"`[^`\n]+`|```", verification):
            problems.append("Verification must contain a concrete command or executable scenario")
        if not code_references(root, text):
            problems.append("body must reference at least one existing implementation file")
        if problems:
            findings.append(f"feature {identifier}: " + "; ".join(problems))
            unresolved += 1
            continue
        documented += 1
    if not features:
        findings.append("feature manifest is empty")
    status = "complete" if features and not findings and unresolved == 0 else "incomplete"
    return {
        "status": status,
        "manifest": path.relative_to(root).as_posix(),
        "feature_count": len(features),
        "documented_count": documented,
        "unresolved_count": unresolved,
        "findings": findings,
    }


def check_project(root: Path, base: str | None, staged: bool) -> tuple[dict[str, Any], int]:
    config = load_config(root)
    if config is None:
        result = {"status": "unconfigured", "project": str(root), "findings": []}
        return result, 0
    if config["status"] == "disabled":
        result = {"status": "disabled", "project": str(root), "findings": []}
        return result, 0

    findings: list[Finding] = []
    required = [root / str(config.get("context_file", "CONTEXT.md")), root / str(config.get("docs_root", "docs")) / "README.md"]
    for path in required:
        if not path.exists():
            findings.append(Finding("error", "missing-canonical-file", f"Missing {path.relative_to(root)}"))

    current_changes = changed_files(root, base=base, staged=staged)
    artifact_paths = doccanon_artifact_paths(config)
    current_changes = {item for item in current_changes if item not in artifact_paths}
    projection = render_agent_entries(root, config, write=False)
    for item in projection["files"]:
        if not item["changed"]:
            continue
        if item.get("legacy"):
            findings.append(
                Finding(
                    "error",
                    "unreconciled-agent-entry",
                    "Hand-written agent entry predates the generated projection; absorb durable rules "
                    'into canonical owners, then run render (or set agent_entry: "" to opt out)',
                    item["path"],
                )
            )
        elif item["exists"]:
            findings.append(
                Finding(
                    "error",
                    "stale-agent-entry",
                    "Agent entry projection is out of date; rerun render",
                    item["path"],
                )
            )
        else:
            findings.append(
                Finding(
                    "error",
                    "missing-agent-entry",
                    "Agent entry projection is missing; run render",
                    item["path"],
                )
            )
    records = document_records(root, config)
    doc_paths = {record.relative for record in records}
    project_version = str(config.get("doccanon_version", "")).strip() or None
    if project_version != skill_version():
        findings.append(
            Finding(
                "warning",
                "project-upgrade-required",
                f"Project was last reconciled with DocCanon {project_version or 'a legacy version'}; "
                "run upgrade status and follow references/upgrading.md",
                CONFIG_NAME,
            )
        )
    context_rel = str(config.get("context_file", "CONTEXT.md"))
    context_record = next((record for record in records if record.relative == context_rel), None)
    if context_record is not None and context_record.authority not in CONTEXT_AUTHORITIES:
        findings.append(
            Finding(
                "warning",
                "unconfirmed-context-file",
                "Context file has no confirmed authority; confirm its terminology and mark it "
                "doccanon_authority: human-confirmed, or rewrite it during migration",
                context_rel,
            )
        )
    docs_root = str(config.get("docs_root", "docs")).strip("/")
    plans_prefix = docs_root + "/plans/"
    for record in records:
        if record.authority == "plan":
            if record.plan_status in {"shipped", "abandoned"}:
                findings.append(
                    Finding(
                        "warning",
                        "inactive-plan-not-retired",
                        "Plan is shipped or abandoned but still routed; retire it by marking "
                        "doccanon_authority: snapshot or historical",
                        record.relative,
                    )
                )
            elif record.plan_status is not None and record.plan_status not in PLAN_STATUSES:
                findings.append(
                    Finding(
                        "warning",
                        "invalid-plan-status",
                        f"Unknown doccanon_status {record.plan_status!r}; use active, ready, shipped, or abandoned",
                        record.relative,
                    )
                )
            elif record.plan_status is None:
                findings.append(
                    Finding(
                        "warning",
                        "missing-plan-status",
                        "Plan must declare doccanon_status: active, ready, shipped, or abandoned",
                        record.relative,
                    )
                )
        elif record.relative.startswith(plans_prefix) and record.authority == "unclassified":
            findings.append(
                Finding(
                    "warning",
                    "unclassified-plan-document",
                    "Documents under the plans area must declare doccanon_authority: plan",
                    record.relative,
                )
            )
    unknown_authorities: dict[str, list[str]] = {}
    for record in records:
        if record.authority not in DECLARED_AUTHORITIES:
            unknown_authorities.setdefault(record.authority, []).append(record.relative)
    for authority, paths in sorted(unknown_authorities.items()):
        findings.append(
            Finding(
                "warning",
                "invalid-authority",
                f"Unknown doccanon_authority {authority!r} on {len(paths)} document(s); use one of "
                + ", ".join(sorted(DECLARED_AUTHORITIES))
                + ", or remove the field",
                files=paths[:20],
            )
        )
    adr_prefix = docs_root + "/adr/"
    unclassified_decisions = [
        record.relative
        for record in records
        if record.relative.startswith(adr_prefix) and record.authority == "unclassified"
    ]
    if unclassified_decisions:
        findings.append(
            Finding(
                "warning",
                "unclassified-decision-record",
                f"{len(unclassified_decisions)} decision record(s) declare no authority; accepted "
                "decisions use doccanon_authority: append-only",
                files=unclassified_decisions[:20],
            )
        )
    registry_summary, registry_problems = registry_report(root, config, records)
    findings.extend(registry_problems)
    archive_rel = archive_root_relative(config)
    if archive_rel and (root / archive_rel).is_dir() and not search_ignore_covers(root, archive_rel):
        findings.append(
            Finding(
                "warning",
                "archive-not-search-excluded",
                "Archive root exists but no search ignore file excludes it; run retire or add it to .ignore",
                archive_rel + "/",
            )
        )
    current_state = [record for record in records if record.authority == "current-state"]
    covered_domains = sorted({domain for record in current_state for domain in record.domains})
    required_domains = sorted({str(item) for item in config.get("required_domains", [])})
    verified_documents = 0

    for record in current_state:
        rel = record.relative
        if not record.covers:
            findings.append(Finding("error", "missing-coverage", "Current-state document has no doccanon_covers patterns", rel))
            continue
        if not record.domains:
            findings.append(Finding("error", "missing-domain", "Current-state document has no doccanon_domains", rel))
            continue
        anchor = record.verified_at
        if not anchor or anchor in {"unverified", "none"}:
            findings.append(Finding("error", "missing-anchor", "Current-state document has no verified Git revision", rel))
            continue
        if not revision_exists(root, anchor):
            findings.append(Finding("error", "invalid-anchor", f"Unknown doccanon_verified_at revision: {anchor}", rel))
            continue
        if not revision_is_ancestor(root, anchor):
            findings.append(Finding("error", "foreign-branch-anchor", "Verified revision is not an ancestor of the current branch", rel))
            continue
        text = record.path.read_text(encoding="utf-8", errors="replace")
        quality_problems = current_state_quality_problems(root, text)
        if quality_problems:
            findings.append(
                Finding(
                    "error",
                    "thin-current-state-document",
                    "; ".join(quality_problems),
                    rel,
                )
            )
            continue
        verified_documents += 1

        relevant = {
            item
            for item in current_changes
            if item not in doc_paths and item not in artifact_paths and not is_repo_meta(item) and match_any(item, record.covers)
        }
        if not staged and not base:
            relevant.update(
                item
                for item in diff_since(root, anchor)
                if item not in doc_paths and item not in artifact_paths and not is_repo_meta(item) and match_any(item, record.covers)
            )

        if relevant and rel not in current_changes:
            findings.append(
                Finding(
                    "error",
                    "stale-document",
                    "Covered implementation changed without a corresponding document update",
                    rel,
                    sorted(relevant),
                )
            )
        elif relevant and rel in current_changes:
            findings.append(
                Finding(
                    "info",
                    "pending-sync",
                    "Document changed alongside covered implementation; verify semantics before completion",
                    rel,
                    sorted(relevant),
                )
            )

    missing_domains = sorted(set(required_domains) - set(covered_domains))
    if missing_domains:
        findings.append(
            Finding("error", "missing-domain-coverage", "Required canonical domains have no verified current-state owner", files=missing_domains)
        )

    manifest_report: dict[str, Any] | None = None
    if config.get("migration_manifest"):
        manifest_report = migration_manifest_status(root, str(config["migration_manifest"]))
        if manifest_report["status"] != "complete":
            findings.append(
                Finding("error", "incomplete-migration", "Migration manifest is missing, incomplete, or unresolved", str(config["migration_manifest"]))
            )
        if manifest_report.get("missing_source_count"):
            findings.append(
                Finding(
                    "warning",
                    "migration-source-missing",
                    f"{manifest_report['missing_source_count']} migration manifest source(s) no longer exist; "
                    "provenance now relies on Git history or removed material",
                    str(config["migration_manifest"]),
                )
            )
        if manifest_report.get("sources_in_tree_count"):
            findings.append(
                Finding(
                    "warning",
                    "legacy-sources-in-tree",
                    f"{manifest_report['sources_in_tree_count']} non-integrated migration source(s) still live "
                    "in the searchable tree; review and retire each with the helper",
                    str(config["migration_manifest"]),
                )
            )

    feature_report: dict[str, Any] | None = None
    if config.get("feature_manifest"):
        feature_report = feature_manifest_status(root, str(config["feature_manifest"]))
        if feature_report["status"] != "complete":
            findings.append(
                Finding("error", "incomplete-feature-library", "Feature manifest or one of its current feature contracts is incomplete", str(config["feature_manifest"]))
            )
    elif "features" in required_domains:
        findings.append(
            Finding("error", "missing-feature-manifest", "The features domain requires a per-feature manifest", DEFAULT_FEATURE_MANIFEST)
        )

    maturity = str(config.get("maturity", "bootstrapping"))
    if not current_state:
        findings.append(
            Finding("warning", "no-current-state-coverage", "No current-state document is linked to implementation coverage")
        )
    if maturity != "governed":
        status = "bootstrap-incomplete"
    elif not current_state or verified_documents == 0 or any(item.level == "error" for item in findings):
        status = "stale"
    else:
        status = "synchronized"
    result = {
        "status": status,
        "maturity": maturity,
        "project": str(root),
        "head": git_head(root),
        "branch": branch_context(root, config, base),
        "changed_files": sorted(current_changes),
        "coverage": {
            "current_state_documents": len(current_state),
            "verified_documents": verified_documents,
            "covered_domains": covered_domains,
            "required_domains": required_domains,
            "missing_domains": missing_domains,
        },
        "migration": manifest_report,
        "features": feature_report,
        "registry": registry_summary,
        "findings": [asdict(item) for item in findings],
    }
    return result, 0 if status == "synchronized" else 1


def is_probably_text(path: Path, max_bytes: int = 512_000) -> tuple[bool, str]:
    try:
        if path.stat().st_size > max_bytes:
            return False, ""
        data = path.read_bytes()
    except (OSError, UnicodeError):
        return False, ""
    if b"\x00" in data[:8192]:
        return False, ""
    try:
        return True, data.decode("utf-8")
    except UnicodeDecodeError:
        return False, ""


def tracked_and_untracked_files(root: Path) -> list[Path]:
    try:
        output = run_git(root, ["ls-files", "-co", "--exclude-standard", "-z"])
        names = [name for name in output.split("\x00") if name]
        return [root / name for name in names if (root / name).is_file()]
    except DocCanonError:
        result: list[Path] = []
        for path in root.rglob("*"):
            if path.is_file() and not any(part in EXCLUDED_PARTS for part in path.relative_to(root).parts):
                result.append(path)
        return result


def document_score(path: Path, root: Path, text: str) -> tuple[int, list[str]]:
    rel = path.relative_to(root).as_posix()
    lower_name = rel.lower()
    lower_sample = text[:80_000].lower()
    signals: list[str] = []
    score = 0
    if path.suffix.lower() in DOC_EXTENSIONS:
        score += 3
        signals.append("documentation-like extension")
    if re.search(r"(?m)^#{1,6}\s+\S", text):
        score += 2
        signals.append("structured headings")
    name_hits = sorted(word for word in DOC_WORDS if word in lower_name)
    content_hits = sorted(word for word in DOC_WORDS if re.search(rf"\b{re.escape(word)}\b", lower_sample))
    if name_hits:
        score += min(4, len(name_hits) * 2)
        signals.append("name: " + ", ".join(name_hits[:4]))
    if content_hits:
        score += min(4, len(content_hits))
        signals.append("content: " + ", ".join(content_hits[:4]))
    if re.search(r"(?im)^(status|context|decision|consequences|requirements|architecture)\s*:", text):
        score += 2
        signals.append("governance fields")
    return score, signals


def inventory(root: Path, limit: int) -> dict[str, Any]:
    candidates: list[dict[str, Any]] = []
    config = load_config(root)
    excluded = {CONFIG_NAME, DEFAULT_MIGRATION_MANIFEST}
    if config and config.get("migration_manifest"):
        excluded.add(str(config["migration_manifest"]))
    archive_rel = archive_root_relative(config) if config else ""
    archive_prefix = archive_rel + "/" if archive_rel else None
    for path in tracked_and_untracked_files(root):
        relative = path.relative_to(root).as_posix()
        if relative in excluded:
            continue
        if archive_prefix and (relative == archive_rel or relative.startswith(archive_prefix)):
            continue
        rel_parts = path.relative_to(root).parts
        if any(part in EXCLUDED_PARTS for part in rel_parts):
            continue
        readable, text = is_probably_text(path)
        if not readable:
            continue
        score, signals = document_score(path, root, text)
        if score < 3:
            continue
        stat = path.stat()
        candidates.append(
            {
                "path": path.relative_to(root).as_posix(),
                "score": score,
                "signals": signals,
                "bytes": stat.st_size,
                "modified_at": datetime.fromtimestamp(stat.st_mtime, timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
            }
        )
    candidates.sort(key=lambda item: (-item["score"], item["path"]))
    return {
        "project": str(root),
        "candidate_count": len(candidates),
        "truncated": len(candidates) > limit,
        "candidates": candidates[:limit],
        "instruction": "Classify candidates semantically; paths and scores are weak discovery signals only.",
    }


def initialize_migration_manifest(
    root: Path,
    manifest: str,
    limit: int,
    allow_feature_branch: bool = False,
    allow_dirty: bool = False,
) -> dict[str, Any]:
    path = (root / manifest).resolve()
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise DocCanonError("Migration manifest must be inside the project") from exc
    if path.exists():
        report = migration_manifest_status(root, manifest)
        report["created"] = False
        return report
    config = load_config(root)
    branch = branch_context(root, config)
    if branch["kind"] == "feature" and not allow_feature_branch:
        raise DocCanonError(
            f"Refusing repository-wide migration on feature branch {branch['current_branch']}; "
            "use the integration branch or pass --allow-feature-branch explicitly"
        )
    if branch["dirty"] and not allow_dirty:
        raise DocCanonError("Refusing migration in a dirty worktree; isolate or finish existing work, or pass --allow-dirty explicitly")
    scanned = inventory(root, limit)
    if scanned["truncated"]:
        raise DocCanonError("Inventory was truncated; rerun migrate scan with a larger --limit")
    entries = [
        {
            "source": item["path"],
            "classification": "unknown",
            "target": None,
            "action": "review",
            "status": "unresolved",
            "confidence": "low",
            "evidence": item["signals"],
            "conflicts": [],
            "requires_review": True,
        }
        for item in scanned["candidates"]
    ]
    payload = {
        "schema_version": 2,
        "source_revision": git_head(root),
        "candidate_count": scanned["candidate_count"],
        "entries": entries,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    report = migration_manifest_status(root, manifest)
    report["created"] = True
    return report


def tokens(value: str) -> set[str]:
    result: set[str] = set()
    for token in WORD_RE.findall(value):
        lower = token.lower()
        runs = CJK_RUN_RE.findall(lower)
        if not runs:
            if len(lower) > 1 and lower not in CONTEXT_STOP_WORDS:
                result.add(lower)
            continue
        for run in runs:
            if len(run) == 1:
                result.add(run)
            else:
                result.update(run[index : index + 2] for index in range(len(run) - 1))
        for piece in WORD_RE.findall(CJK_CHAR_RE.sub(" ", lower)):
            if len(piece) > 1 and piece not in CONTEXT_STOP_WORDS:
                result.add(piece)
    return result


def code_references(root: Path, text: str) -> list[str]:
    refs: set[str] = set()
    for candidate in CODE_REF_RE.findall(text):
        cleaned = candidate.strip().split("#", 1)[0]
        if len(cleaned) > 240 or "\n" in cleaned:
            continue
        path = root / cleaned
        if path.exists() and path.is_file():
            refs.add(cleaned)
    return sorted(refs)


def markdown_sections(text: str) -> dict[str, str]:
    matches = list(re.finditer(r"(?m)^##\s+(.+?)\s*$", text))
    sections: dict[str, str] = {}
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        sections[match.group(1).strip().lower()] = text[match.end():end].strip()
    return sections


def current_state_quality_problems(root: Path, text: str) -> list[str]:
    body = text
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end >= 0:
            body = text[end + 5:]
    compact = re.sub(r"\s+", " ", body).strip()
    problems: list[str] = []
    if len(compact) < 160:
        problems.append("body is too thin to be a substantive current-state contract")
    if not code_references(root, text):
        problems.append("body must reference at least one existing implementation file")
    verification = markdown_sections(body).get("verification", "")
    if not verification:
        problems.append("missing Verification section")
    elif not re.search(r"`[^`\n]+`|```", verification):
        problems.append("Verification must contain a concrete command or executable scenario")
    return problems


def context_bundle(root: Path, intent: str, limit: int, include_historical: bool = False) -> dict[str, Any]:
    config = load_config(root)
    if config is None:
        return {"status": "unconfigured", "documents": []}
    if config["status"] == "disabled":
        return {"status": "disabled", "documents": []}
    query = tokens(intent)
    excluded_historical = 0
    authority_weight = {"current-state": 60, "human-confirmed": 45, "plan": 30, "append-only": 25, "generated": 5}
    context_rel = str(config.get("context_file", "CONTEXT.md"))
    candidates: list[dict[str, Any]] = []
    for record in document_records(root, config):
        path = record.path
        text = path.read_text(encoding="utf-8", errors="replace")
        rel = record.relative
        authority = record.authority
        if authority not in CONTEXT_AUTHORITIES and not include_historical:
            excluded_historical += 1
            continue
        name_hits = sorted(query & tokens(rel))
        heading_text = " ".join(re.findall(r"(?m)^#{1,6}\s+(.+)$", text))
        heading_hits = sorted(query & tokens(heading_text))
        matched = sorted(query & tokens(text[:120_000]))
        candidates.append(
            {
                "path": rel,
                "authority": authority,
                "verified_at": record.verified_at,
                "domains": record.domains,
                "name_hits": name_hits,
                "heading_hits": heading_hits,
                "matched_terms": matched,
                "code_references": code_references(root, text),
            }
        )
    total = max(len(candidates), 1)
    document_frequency: dict[str, int] = {}
    for item in candidates:
        for term in set(item["matched_terms"]) | set(item["name_hits"]) | set(item["heading_hits"]):
            document_frequency[term] = document_frequency.get(term, 0) + 1

    def term_weight(term: str) -> float:
        return 1 + log((total + 1) / (document_frequency.get(term, 0) + 1))

    ranked: list[dict[str, Any]] = []
    for item in candidates:
        relevance = (
            sum(term_weight(term) * 6 for term in item["name_hits"])
            + sum(term_weight(term) * 3 for term in item["heading_hits"])
            + sum(term_weight(term) for term in item["matched_terms"])
        )
        if item["path"] == context_rel and relevance:
            relevance += 2
        score = round(relevance + authority_weight.get(item["authority"], -25), 3)
        if relevance or not query:
            ranked.append(
                {
                    "path": item["path"],
                    "score": score,
                    "authority": item["authority"],
                    "verified_at": item["verified_at"],
                    "domains": item["domains"],
                    "matched_terms": item["matched_terms"],
                    "code_references": item["code_references"],
                }
            )
    ranked.sort(key=lambda item: (-item["score"], item["path"]))
    check, _ = check_project(root, base=None, staged=False)
    return {
        "status": check["status"],
        "intent": intent,
        "query_terms": sorted(query),
        "documents": ranked[:limit],
        "excluded_historical_documents": excluded_historical,
        "include_historical": include_historical,
        "freshness_findings": check.get("findings", []),
    }


def update_frontmatter(path: Path, values: dict[str, Any]) -> None:
    text = path.read_text(encoding="utf-8")
    existing: dict[str, Any] = {}
    body = text
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end >= 0:
            existing = parse_simple_yaml(text[4:end])
            body = text[end + 5 :]
    existing.update(values)
    lines = ["---"]
    for key, value in existing.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"  - {json.dumps(str(item), ensure_ascii=False)}" for item in value)
        else:
            lines.append(f"{key}: {value}")
    lines.extend(["---", body.lstrip("\n")])
    path.write_text("\n".join(lines), encoding="utf-8")


def mark_verified(
    root: Path,
    document: str,
    covers: list[str] | None,
    domains: list[str] | None,
    feature: str | None = None,
) -> dict[str, Any]:
    path = (root / document).resolve()
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise DocCanonError("Document must be inside the project") from exc
    if not path.is_file():
        raise DocCanonError(f"Document not found: {document}")
    if not covers:
        raise DocCanonError("mark-verified requires at least one --covers pattern")
    if not domains:
        raise DocCanonError("mark-verified requires at least one --domain")
    revision = git_head(root)
    if not revision:
        raise DocCanonError("mark-verified requires a Git commit")
    values: dict[str, Any] = {
        "doccanon_authority": "current-state",
        "doccanon_verified_at": revision,
    }
    values["doccanon_covers"] = sorted(set(covers))
    values["doccanon_domains"] = sorted(set(domains))
    if feature:
        values["doccanon_feature"] = feature
    update_frontmatter(path, values)
    return {
        "status": "marked",
        "document": document,
        "verified_at": revision,
        "covers": sorted(set(covers)),
        "domains": sorted(set(domains)),
        "feature": feature,
    }


def promote(
    root: Path,
    domains: list[str] | None,
    manifest: str | None,
    feature_manifest: str | None,
) -> dict[str, Any]:
    config = load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("promote requires an enabled DocCanon project")
    required_domains = sorted(set(domains or []))
    if not required_domains:
        raise DocCanonError("promote requires at least one --domain")
    records = document_records(root, config)
    valid = [
        record
        for record in records
        if record.authority == "current-state"
        and record.covers
        and record.domains
        and record.verified_at
        and revision_exists(root, record.verified_at)
        and revision_is_ancestor(root, record.verified_at)
        and not current_state_quality_problems(
            root,
            record.path.read_text(encoding="utf-8", errors="replace"),
        )
    ]
    covered_domains = {domain for record in valid for domain in record.domains}
    missing = sorted(set(required_domains) - covered_domains)
    if not valid:
        raise DocCanonError("No verified current-state documents exist")
    if missing:
        raise DocCanonError("Missing verified current-state owners for domains: " + ", ".join(missing))
    if manifest:
        report = migration_manifest_status(root, manifest)
        if report["status"] != "complete":
            raise DocCanonError(
                f"Migration manifest is not complete: {report['unresolved_count']} unresolved, "
                f"{report['mapped_count']}/{report['candidate_count']} mapped"
            )
    resolved_feature_manifest = feature_manifest
    if "features" in required_domains:
        resolved_feature_manifest = resolved_feature_manifest or DEFAULT_FEATURE_MANIFEST
        feature_report = feature_manifest_status(root, resolved_feature_manifest)
        if feature_report["status"] != "complete":
            raise DocCanonError(
                f"Feature library is not complete: {feature_report['documented_count']}/"
                f"{feature_report['feature_count']} documented, {feature_report['unresolved_count']} unresolved"
            )
    config.update(
        {
            "maturity": "governed",
            "required_domains": required_domains,
            "migration_manifest": manifest,
            "feature_manifest": resolved_feature_manifest,
        }
    )
    write_config(root, config)
    render_agent_entries(root, config, write=True, allow_adoption=False)
    if str(config.get("registry", "")).strip():
        build_registry(root, config)
    checked, _ = check_project(root, base=None, staged=False)
    if checked["status"] != "synchronized":
        config["maturity"] = "bootstrapping"
        write_config(root, config)
        raise DocCanonError("Promotion checks did not pass; project remains bootstrapping")
    return {
        "status": "governed",
        "required_domains": required_domains,
        "verified_documents": len(valid),
        "migration_manifest": manifest,
        "feature_manifest": resolved_feature_manifest,
    }


def preflight(root: Path, target: str | None) -> tuple[dict[str, Any], int]:
    config = load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("preflight requires an enabled DocCanon project")
    branch = branch_context(root, config, target)
    base_ref = str(branch["base_ref"])
    if not revision_exists(root, base_ref):
        raise DocCanonError(f"Cannot resolve preflight target: {base_ref}")
    checked, _ = check_project(root, base=base_ref, staged=False)
    changed = changed_files(root, base=base_ref, staged=False)
    artifact_paths = doccanon_artifact_paths(config)
    changed = {item for item in changed if item not in artifact_paths}
    affected: list[dict[str, Any]] = []
    stale_features: list[str] = []
    feature_manifest = str(config.get("feature_manifest", DEFAULT_FEATURE_MANIFEST))
    manifest_path = root / feature_manifest
    if manifest_path.is_file():
        payload = json.loads(manifest_path.read_text(encoding="utf-8"))
        for feature in payload.get("features", []):
            if not isinstance(feature, dict) or feature.get("status") != "current":
                continue
            patterns = feature.get("code_patterns", [])
            if isinstance(patterns, str):
                patterns = [patterns]
            code_changes = sorted(
                item
                for item in changed
                if not is_repo_meta(item) and match_any(item, [str(pattern) for pattern in patterns])
            )
            if not code_changes:
                continue
            document = str(feature.get("document", ""))
            updated = document in changed
            identifier = str(feature.get("id", ""))
            affected.append(
                {
                    "id": identifier,
                    "document": document,
                    "document_updated": updated,
                    "changed_files": code_changes,
                }
            )
            if not updated:
                stale_features.append(identifier)
    records = document_records(root, config)
    changed_canonical_docs = sorted(
        record.relative
        for record in records
        if record.relative in changed and record.authority in CONTEXT_AUTHORITIES
    )
    blockers: list[str] = []
    if checked["status"] != "synchronized":
        blockers.append("doccanon-check")
    if stale_features:
        blockers.append("stale-feature-docs")
    if branch["dirty"]:
        blockers.append("dirty-worktree")
    if branch["behind"]:
        blockers.append("behind-target")
    status = "ready" if not blockers else "blocked"
    result = {
        "status": status,
        "branch": branch,
        "target": base_ref,
        "changed_files": sorted(changed),
        "affected_features": affected,
        "stale_features": stale_features,
        "blockers": blockers,
        "changed_canonical_docs": changed_canonical_docs,
        "doccanon_check": checked,
    }
    return result, 0 if status == "ready" else 1


def documentation_impact(root: Path, target: str | None) -> dict[str, Any]:
    config = load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("sync requires an enabled DocCanon project")
    branch = branch_context(root, config, target)
    base_ref = str(branch["base_ref"])
    if not revision_exists(root, base_ref):
        raise DocCanonError(f"Cannot resolve sync target: {base_ref}")
    changed = changed_files(root, base=base_ref, staged=False)
    docs_root = str(config.get("docs_root", "docs")).rstrip("/") + "/"
    context_file = str(config.get("context_file", "CONTEXT.md"))
    artifact_paths = doccanon_artifact_paths(config)
    implementation_files = sorted(
        path
        for path in changed
        if path != CONFIG_NAME
        and path != context_file
        and path not in artifact_paths
        and not path.startswith(docs_root)
        and not is_repo_meta(path)
    )

    feature_patterns: list[str] = []
    affected_features: list[dict[str, Any]] = []
    feature_manifest = str(config.get("feature_manifest", DEFAULT_FEATURE_MANIFEST))
    feature_manifest_path = root / feature_manifest
    if feature_manifest_path.is_file():
        try:
            feature_payload = json.loads(feature_manifest_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise DocCanonError(f"Invalid feature manifest: {exc}") from exc
        for feature in feature_payload.get("features", []):
            if not isinstance(feature, dict) or feature.get("status") != "current":
                continue
            patterns = feature.get("code_patterns", [])
            if isinstance(patterns, str):
                patterns = [patterns]
            patterns = [str(pattern) for pattern in patterns]
            feature_patterns.extend(patterns)
            matched = sorted(path for path in implementation_files if match_any(path, patterns))
            if not matched:
                continue
            document = str(feature.get("document", ""))
            affected_features.append(
                {
                    "id": str(feature.get("id", "")),
                    "document": document,
                    "document_updated": document in changed,
                    "changed_files": matched,
                }
            )

    current_owners: list[dict[str, Any]] = []
    owner_patterns: list[str] = []
    known_domains: set[str] = set()
    for record in document_records(root, config):
        if record.authority != "current-state" or not record.covers:
            continue
        known_domains.update(record.domains)
        owner_patterns.extend(record.covers)
        matched = sorted(path for path in implementation_files if match_any(path, record.covers))
        if matched:
            current_owners.append(
                {
                    "document": record.relative,
                    "domains": record.domains,
                    "document_updated": record.relative in changed,
                    "changed_files": matched,
                }
            )

    required = config.get("required_domains", [])
    if isinstance(required, str):
        required = [required]
    review_domains = sorted(set(str(item) for item in required) | known_domains)
    inferred_domains = sorted({domain for owner in current_owners for domain in owner["domains"]})
    all_patterns = feature_patterns + owner_patterns
    unmapped = sorted(path for path in implementation_files if not match_any(path, all_patterns))
    stale_feature_docs = sorted(item["id"] for item in affected_features if not item["document_updated"])
    stale_owner_docs = sorted(item["document"] for item in current_owners if not item["document_updated"])
    changed_canonical_docs = sorted(
        record.relative
        for record in document_records(root, config)
        if record.relative in changed and record.authority in CONTEXT_AUTHORITIES
    )
    return {
        "status": "no-changes" if not changed else "review-required",
        "branch": branch,
        "target": base_ref,
        "changed_files": sorted(changed),
        "implementation_files": implementation_files,
        "affected_features": affected_features,
        "affected_current_state_owners": current_owners,
        "inferred_domains": inferred_domains,
        "review_domains": review_domains,
        "unmapped_implementation_files": unmapped,
        "stale_feature_docs": stale_feature_docs,
        "stale_owner_docs": stale_owner_docs,
        "changed_canonical_docs": changed_canonical_docs,
    }


def parse_review_receipts(values: list[str] | None, label: str) -> dict[str, str]:
    receipts: dict[str, str] = {}
    for value in values or []:
        key, separator, reason = value.partition("=")
        key = key.strip()
        reason = reason.strip()
        if not separator or not key or len(reason) < 8:
            raise DocCanonError(f"{label} requires NAME=reason with a substantive reason")
        receipts[key] = reason
    return receipts


def complete_sync(
    root: Path,
    target: str | None,
    affected_domains: list[str] | None,
    excluded_domains: list[str] | None,
    excluded_files: list[str] | None,
    title: str | None,
    summary: str | None,
    verification: list[str] | None,
    skip_history: str | None,
    release_version: str | None,
    release_evidence: list[str] | None,
    limitations: list[str] | None,
) -> tuple[dict[str, Any], int]:
    config = load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("sync complete requires an enabled DocCanon project")
    if config.get("maturity", "bootstrapping") != "governed":
        raise DocCanonError("sync complete requires a governed project; finish bootstrap first")
    impact = documentation_impact(root, target)
    domain_exclusions = parse_review_receipts(excluded_domains, "--exclude-domain")
    file_exclusions = parse_review_receipts(excluded_files, "--exclude-file")
    declared_domains = set(affected_domains or [])
    inferred_domains = set(impact["inferred_domains"])
    review_domains = set(impact["review_domains"])
    affected = inferred_domains | declared_domains

    blockers: list[dict[str, Any]] = []
    for domain in sorted(review_domains):
        if domain not in affected and domain not in domain_exclusions:
            blockers.append({"code": "unreviewed-domain", "domain": domain})
    for domain in sorted(set(domain_exclusions) & affected):
        blockers.append({"code": "conflicting-domain-review", "domain": domain})

    changed_docs = set(impact["changed_canonical_docs"])
    records = document_records(root, config)
    for domain in sorted(declared_domains):
        owners = [record.relative for record in records if record.authority == "current-state" and domain in record.domains]
        if not any(owner in changed_docs for owner in owners):
            blockers.append({"code": "affected-domain-without-update", "domain": domain, "owners": owners})
    for document in impact["stale_owner_docs"]:
        blockers.append({"code": "stale-current-state-owner", "document": document})
    for feature in impact["stale_feature_docs"]:
        blockers.append({"code": "stale-feature-contract", "feature": feature})
    for path in impact["unmapped_implementation_files"]:
        if path not in file_exclusions:
            blockers.append({"code": "unmapped-implementation-file", "file": path})
    unknown_file_receipts = sorted(set(file_exclusions) - set(impact["unmapped_implementation_files"]))
    for path in unknown_file_receipts:
        blockers.append({"code": "unused-file-exclusion", "file": path})

    if not verification:
        blockers.append({"code": "missing-verification"})
    if skip_history:
        if len(skip_history.strip()) < 8:
            blockers.append({"code": "weak-history-exclusion"})
        if title or summary:
            blockers.append({"code": "conflicting-history-decision"})
    elif not title or not summary:
        blockers.append({"code": "missing-development-record"})
    if release_version and not release_evidence:
        blockers.append({"code": "release-without-direct-evidence"})
    plan_readiness: list[dict[str, Any]] = []
    if release_version:
        for record in records:
            if record.authority != "plan" or record.plan_target != release_version:
                continue
            status = record.plan_status or "active"
            plan_readiness.append({"plan": record.relative, "status": status, "target": release_version})
            if status not in RELEASABLE_PLAN_STATUSES:
                blockers.append(
                    {"code": "plan-not-ready-for-release", "plan": record.relative, "status": status}
                )

    agent_entry = render_agent_entries(root, config, write=True, allow_adoption=False)
    for item in agent_entry["files"]:
        if item.get("blocked_legacy"):
            blockers.append({"code": "unreconciled-agent-entry", "path": item["path"]})
    registry_result = None
    if str(config.get("registry", "")).strip():
        registry_result = build_registry(root, config)
    checked, _ = check_project(root, base=impact["target"], staged=False)
    if checked["status"] != "synchronized":
        blockers.append({"code": "doccanon-check", "status": checked["status"]})
    if blockers:
        return {
            "status": "blocked",
            "impact": impact,
            "blockers": blockers,
            "agent_entry": agent_entry,
            "registry": registry_result,
            "release_readiness": plan_readiness,
            "doccanon_check": checked,
        }, 1

    impact_receipt = {
        "affected_domains": sorted(affected),
        "excluded_domains": domain_exclusions,
        "excluded_unmapped_files": file_exclusions,
        "changed_canonical_docs": impact["changed_canonical_docs"],
    }
    feature_ids = [item["id"] for item in impact["affected_features"]]
    development_log = None
    if not skip_history:
        development_log = append_development_log(
            root,
            str(title),
            str(summary),
            feature_ids,
            verification,
            impact=impact_receipt,
        )
    release_log = None
    if release_version:
        release_log = write_release_log(
            root,
            release_version,
            str(summary or title or f"Release {release_version}"),
            feature_ids,
            list(verification or []) + list(release_evidence or []),
            limitations,
        )
    return {
        "status": "synchronized",
        "impact": impact,
        "impact_receipt": impact_receipt,
        "development_log": development_log,
        "release_log": release_log,
        "history_exclusion": skip_history,
        "agent_entry": agent_entry,
        "registry": registry_result,
        "release_readiness": plan_readiness,
        "doccanon_check": checked,
    }, 0


def append_development_log(
    root: Path,
    title: str,
    summary: str,
    features: list[str] | None,
    verification: list[str] | None,
    impact: dict[str, Any] | None = None,
) -> dict[str, Any]:
    config = load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("development log requires an enabled DocCanon project")
    branch = branch_context(root, config)
    record_payload = {
        "kind": "development",
        "title": title.strip(),
        "summary": summary.strip(),
        "features": sorted(features or []),
        "verification": sorted(verification or []),
        "impact": impact or {},
        "branch": branch["current_branch"],
        "base": branch["base_ref"],
        "commit": branch["head"],
    }
    record_id = hashlib.sha256(
        json.dumps(record_payload, ensure_ascii=False, sort_keys=True).encode("utf-8")
    ).hexdigest()[:16]
    marker = f"<!-- doccanon-record: development:{record_id} -->"
    timestamp = datetime.now(timezone.utc).replace(microsecond=0)
    log_root = root / str(config.get("development_log_root", "docs/development"))
    if log_root.exists():
        for existing in sorted(log_root.glob("*.md")):
            if marker in existing.read_text(encoding="utf-8"):
                return {
                    "status": "already-recorded",
                    "kind": "development",
                    "path": existing.relative_to(root).as_posix(),
                    "record_id": record_id,
                    "branch": branch,
                }
    path = log_root / f"{timestamp:%Y-%m}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.write_text(
            "---\ndoccanon_authority: snapshot\ndoccanon_log: development\n---\n\n# Development log\n",
            encoding="utf-8",
        )
    entry = [
        "",
        marker,
        f"## {timestamp:%Y-%m-%d %H:%M UTC} — {title}",
        "",
        f"- Branch: `{branch['current_branch']}`",
        f"- Base: `{branch['base_ref']}`",
        f"- Commit: `{branch['head']}`",
        "",
        summary.strip(),
    ]
    if features:
        entry.extend(["", "### Features", "", *[f"- `{item}`" for item in features]])
    if verification:
        entry.extend(["", "### Verification", "", *[f"- {item}" for item in verification]])
    if impact:
        entry.extend(["", "### Documentation impact", ""])
        for domain in impact.get("affected_domains", []):
            entry.append(f"- Affected domain: `{domain}`")
        for document in impact.get("changed_canonical_docs", []):
            entry.append(f"- Updated owner: `{document}`")
        for domain, reason in impact.get("excluded_domains", {}).items():
            entry.append(f"- Excluded domain `{domain}`: {reason}")
        for excluded_path, reason in impact.get("excluded_unmapped_files", {}).items():
            entry.append(f"- Excluded file `{excluded_path}`: {reason}")
    with path.open("a", encoding="utf-8") as handle:
        handle.write("\n".join(entry) + "\n")
    return {
        "status": "recorded",
        "kind": "development",
        "path": path.relative_to(root).as_posix(),
        "record_id": record_id,
        "branch": branch,
    }


def write_release_log(
    root: Path,
    version: str,
    summary: str,
    features: list[str] | None,
    verification: list[str] | None,
    limitations: list[str] | None,
) -> dict[str, Any]:
    config = load_config(root)
    if config is None or config["status"] != "enabled":
        raise DocCanonError("release log requires an enabled DocCanon project")
    safe_version = re.sub(r"[^A-Za-z0-9._-]+", "-", version).strip("-")
    if not safe_version:
        raise DocCanonError("Release version must contain a safe filename character")
    branch = branch_context(root, config)
    record_payload = {
        "kind": "release",
        "version": version,
        "summary": summary.strip(),
        "features": sorted(features or []),
        "verification": sorted(verification or []),
        "limitations": sorted(limitations or []),
        "branch": branch["current_branch"],
        "commit": branch["head"],
    }
    record_id = hashlib.sha256(
        json.dumps(record_payload, ensure_ascii=False, sort_keys=True).encode("utf-8")
    ).hexdigest()[:16]
    marker = f"<!-- doccanon-record: release:{record_id} -->"
    log_root = root / str(config.get("release_log_root", "docs/releases"))
    path = log_root / f"{safe_version}.md"
    if path.exists():
        if marker in path.read_text(encoding="utf-8"):
            return {
                "status": "already-recorded",
                "kind": "release",
                "path": path.relative_to(root).as_posix(),
                "record_id": record_id,
                "branch": branch,
            }
        raise DocCanonError(f"Release log already exists: {path.relative_to(root)}")
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "---",
        "doccanon_authority: snapshot",
        "doccanon_log: release",
        f"doccanon_release: {json.dumps(version, ensure_ascii=False)}",
        "---",
        "",
        marker,
        f"# Release {version}",
        "",
        f"- Date: {datetime.now(timezone.utc):%Y-%m-%d}",
        f"- Source branch: `{branch['current_branch']}`",
        f"- Commit: `{branch['head']}`",
        "",
        "## Summary",
        "",
        summary.strip(),
    ]
    if features:
        lines.extend(["", "## Features", "", *[f"- `{item}`" for item in features]])
    if verification:
        lines.extend(["", "## Verification", "", *[f"- {item}" for item in verification]])
    if limitations:
        lines.extend(["", "## Known limitations", "", *[f"- {item}" for item in limitations]])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {
        "status": "recorded",
        "kind": "release",
        "path": path.relative_to(root).as_posix(),
        "record_id": record_id,
        "branch": branch,
    }


def hook_path(root: Path) -> Path:
    git_dir = run_git(root, ["rev-parse", "--git-path", "hooks"])
    path = Path(git_dir)
    if not path.is_absolute():
        path = root / path
    return path / "pre-commit"


def hook_block(root: Path) -> str:
    helper = Path(__file__).resolve()
    command = " ".join(
        [
            shlex.quote(sys.executable),
            shlex.quote(str(helper)),
            "--project",
            shlex.quote(str(root)),
            "check",
            "--staged",
        ]
    )
    return f"{MANAGED_HOOK_START}\n{command}\n{MANAGED_HOOK_END}"


def manage_hook(root: Path, action: str) -> dict[str, Any]:
    path = hook_path(root)
    if action == "status":
        installed = path.exists() and MANAGED_HOOK_START in path.read_text(encoding="utf-8", errors="replace")
        return {"status": "installed" if installed else "not-installed", "path": str(path)}
    if action == "uninstall":
        if not path.exists():
            return {"status": "not-installed", "path": str(path)}
        text = path.read_text(encoding="utf-8")
        pattern = re.compile(rf"\n?{re.escape(MANAGED_HOOK_START)}.*?{re.escape(MANAGED_HOOK_END)}\n?", re.S)
        cleaned = pattern.sub("\n", text).strip()
        if cleaned in {"", "#!/bin/sh", "#!/usr/bin/env sh"}:
            path.unlink()
        else:
            path.write_text(cleaned + "\n", encoding="utf-8")
        return {"status": "uninstalled", "path": str(path)}

    checked, _ = check_project(root, base=None, staged=False)
    if checked["status"] != "synchronized":
        raise DocCanonError("Install the hook only after the project reaches governed, synchronized status")

    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.exists() else "#!/bin/sh\n"
    block = hook_block(root)
    if MANAGED_HOOK_START in existing:
        pattern = re.compile(rf"{re.escape(MANAGED_HOOK_START)}.*?{re.escape(MANAGED_HOOK_END)}", re.S)
        updated = pattern.sub(block, existing)
    else:
        updated = existing.rstrip() + "\n\n" + block + "\n"
    path.write_text(updated, encoding="utf-8")
    path.chmod(path.stat().st_mode | 0o111)
    return {"status": "installed", "path": str(path)}


def print_result(result: dict[str, Any], as_json: bool) -> None:
    if as_json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return
    status = result.get("status", "ok")
    print(f"DocCanon: {status}")
    for key, value in result.items():
        if key == "status":
            continue
        if key == "findings":
            for item in value:
                location = f" ({item.get('document')})" if item.get("document") else ""
                print(f"- {item['level'].upper()} {item['code']}{location}: {item['message']}")
            continue
        if isinstance(value, (str, int)) or value is None:
            print(f"{key}: {value}")


